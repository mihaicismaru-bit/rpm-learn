import assert from 'node:assert/strict';
import {lesson} from '../canonical/s2b/v2.6/fixture.mjs';
import {LessonPlayerSessionController} from '../canonical/s3/lesson-player/v0.1/session-controller.mjs';
import {S3MemoryEventStore,correctLessonResponse} from '../canonical/s3/lesson-player/v0.1/s3-test-support.mjs';
import {createSpeakingSubmissionService} from '../canonical/s4/speaking/v0.1/speaking-submission.mjs';
import {createHumanReviewBridgeService} from '../canonical/s4/review/v0.1/human-review-bridge.mjs';
import {deriveMasterySnapshot} from '../canonical/s5/mastery/v0.1/mastery-engine.mjs';
import {buildValidatedLearningTimeLedger} from '../canonical/s6/time/v0.1/validated-learning-time-ledger.mjs';
import {buildTeacherLearnerView,createTeacherValidationService} from '../canonical/s7/teacher/v0.1/teacher-os.mjs';
import {buildEmployerLearnerView} from '../canonical/s8/employer/v0.1/employer-os.mjs';
import {buildReportsEvidencePack} from '../canonical/s9/reports/v0.1/reports-evidence-pack.mjs';
import {requireCertificateIssuance,CertificateGateError} from '../canonical/s11/certificate/v0.1/certificate-gate.mjs';

class ReviewStore{constructor(){this.rows=[]}async open(){}async listReviews(){return this.rows.map(x=>structuredClone(x))}async appendReview(r){this.rows.push(structuredClone(r));return {status:'appended'}}}
class ValidationStore{constructor(){this.rows=[]}async open(){}async listValidations(){return this.rows.map(x=>structuredClone(x))}async appendValidation(r){this.rows.push(structuredClone(r));return {status:'appended'}}}
const scope={subjectId:'learner-integration',organisationId:'org-integration',role:'LEARNER'};
const teacher={teacherId:'teacher-integration',organisationId:'org-integration',role:'TEACHER'};
const employer={employerId:'employer-integration',organisationId:'org-integration',role:'EMPLOYER'};
const reviews=new ReviewStore();
const validations=new ValidationStore();
const eventStore=new S3MemoryEventStore({trustedHumanReviewProvider:async()=>reviews.rows});let now=1000;
const controller=new LessonPlayerSessionController({lesson,eventStore,scope,sessionId:'integration',now:()=>++now});
let view=await controller.start();
while(view.currentItem&&view.currentItem.id!=='E06')view=await controller.answer(view.currentItem.id,correctLessonResponse(view.currentItem));
assert.equal(view.currentItem.id,'E06');
const speaking=createSpeakingSubmissionService({lesson,eventStore,scope,sessionId:'integration-speaking',now:()=>++now});
await speaking.submit({itemId:'E06',mediaRef:'demo://integration/e06',clientSubmissionId:'integration-e06'});
view=await controller.refresh();assert.equal(view.status,'AWAITING_HUMAN_REVIEW');
const bridge=createHumanReviewBridgeService({reviewStore:reviews,reviewer:{reviewerId:teacher.teacherId,organisationId:teacher.organisationId,role:'TEACHER'},now:()=>++now});
const speakingEvent=eventStore.events.find(e=>e.type==='SPEAKING_SUBMITTED');
await bridge.review({speakingEvent,clientReviewId:'integration-review',decision:'VALID'});
view=await controller.refresh();
assert.equal(view.status,'ACTIVE');
assert.equal(view.currentItem.id,'E07');
view=await controller.answer(view.currentItem.id,correctLessonResponse(view.currentItem));
assert.equal(view.currentItem.id,'E08');
view=await controller.answer(view.currentItem.id,correctLessonResponse(view.currentItem));
assert.equal(view.status,'READY_TO_COMPLETE');
view=await controller.complete();
assert.equal(view.status,'COMPLETED');
const mastery=deriveMasterySnapshot({lesson,events:eventStore.events,humanReviews:reviews.rows});
const time=buildValidatedLearningTimeLedger({lesson,events:eventStore.events,trustedHumanReviews:reviews.rows});
const teacherView=buildTeacherLearnerView({lesson,events:eventStore.events,masterySnapshot:mastery,learningTimeLedger:time,humanReviews:reviews.rows,teacher});
assert.equal(teacherView.speakingReviewQueue[0].status,'VALID');
assert.equal(teacherView.learnerStatus,'COMPLETED');
const validationService=createTeacherValidationService({validationStore:validations,teacher,now:()=>++now});
const finalValidation=await validationService.validate({teacherView,clientValidationId:'integration-final',validationKind:'FINAL',decision:'VALID'});
assert.equal(finalValidation.decision,'VALID');
assert.equal(finalValidation.certificateAuthority,false);
const employerView=buildEmployerLearnerView({teacherView,teacherValidations:validations.rows,reportIndex:[],employer});
assert.equal(employerView.organisationId,'org-integration');
assert.equal(employerView.learnerAnswerDetailExposed,false);
assert.equal(employerView.validations.finalValidated,true);
const reports=buildReportsEvidencePack({teacherView,employerView,teacherValidations:validations.rows,period:{generatedAt:100,weekLabel:'TEST-WEEK',monthLabel:'TEST-MONTH'}});
assert.equal(reports.finalLearningPathReport.status,'TEACHER_VALIDATED');
assert.throws(()=>requireCertificateIssuance(),e=>e instanceof CertificateGateError&&e.code==='CERTIFICATE_FINAL_LEGAL_APPROVAL_REQUIRED');
console.log('RPM_FUNCTIONAL_PRODUCT_INTEGRATION_PASS learner-speaking-human-review-resume-completion final-teacher-validation employer-reports certificate-fail-closed');
